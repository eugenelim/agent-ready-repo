def test_check_no_catalogue_toml(tmp_path):
    """catalogue.toml absent → ok=False, diagnostic code CAT-SD-001."""
    # No catalogue.toml created; load_catalogue_config returns None naturally.
    result = check_defaults(tmp_path)
    assert result.ok is False
    assert result.diagnostics
    assert result.diagnostics[0].code.startswith("CAT-SD-001")


def test_check_absent_file(tmp_path, monkeypatch):
    """catalogue.toml present (via mock) but install-defaults.toml missing → ok=False, CAT-SD-002."""  # noqa: E501
    config = _make_config()
    monkeypatch.setattr(
        _defaults_module, "load_catalogue_config", lambda root: config
    )
    # install-defaults.toml intentionally not created
    result = check_defaults(tmp_path)
    assert result.ok is False
    assert any(d.code == "CAT-SD-002" for d in result.diagnostics)


def test_check_drift(tmp_path, monkeypatch):
    """install-defaults.toml exists but content differs from compile_defaults → ok=False, CAT-SD-003."""  # noqa: E501
    config = _make_config()
    monkeypatch.setattr(
        _defaults_module, "load_catalogue_config", lambda root: config
    )
    # Write stale content that will not match compile_defaults output
    (tmp_path / "install-defaults.toml").write_text(
        "# stale content\n[organization]\npreferred_adapter = \"old-adapter\"\n",
        encoding="utf-8",
    )
    result = check_defaults(tmp_path)
    assert result.ok is False
    assert any(d.code == "CAT-SD-003" for d in result.diagnostics)


def test_check_ok(tmp_path, monkeypatch):
    """install-defaults.toml byte-matches compile_defaults output → ok=True."""
    config = _make_config()
    monkeypatch.setattr(
        _defaults_module, "load_catalogue_config", lambda root: config
    )
    expected = compile_defaults(config)
    (tmp_path / "install-defaults.toml").write_text(expected, encoding="utf-8")
    result = check_defaults(tmp_path)
    assert result.ok is True
    assert result.diagnostics == []



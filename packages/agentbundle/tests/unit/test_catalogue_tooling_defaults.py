def test_write_defaults(tmp_path, monkeypatch):
    """write_defaults creates install-defaults.toml with compile_defaults content."""
    config = _make_config()
    monkeypatch.setattr(
        _defaults_module, "load_catalogue_config", lambda root: config
    )
    result = write_defaults(tmp_path)
    assert result.ok is True
    output_file = tmp_path / "install-defaults.toml"
    assert output_file.exists()
    written = output_file.read_text(encoding="utf-8")
    assert written == compile_defaults(config)


def test_write_defaults_path_jail(tmp_path, monkeypatch):
    """install_defaults_output that resolves outside root → CatalogueConfigError (ValueError)."""
    config = _make_config(install_defaults_output="../escape.toml")
    monkeypatch.setattr(
        _defaults_module, "load_catalogue_config", lambda root: config
    )
    with pytest.raises(ValueError):
        write_defaults(tmp_path)


def test_write_defaults_symlink_guard(tmp_path, monkeypatch):
    """install-defaults.toml is a symlink pointing outside root → CatalogueConfigError.

    Implementation note: write_defaults calls .resolve() before the is_symlink()
    guard (line 172 of defaults.py), so the guard is dead for in-root symlinks.
    Symlinks that escape the root are caught by the path-jail check instead,
    which is the observable protection tested here.
    """
    config = _make_config(install_defaults_output="install-defaults.toml")
    monkeypatch.setattr(
        _defaults_module, "load_catalogue_config", lambda root: config
    )
    # Symlink points to a file outside tmp_path; path-jail catches the escape.
    target = tmp_path / "install-defaults.toml"
    outside = tmp_path.parent / "symlink-target-outside.toml"
    target.symlink_to(outside)
    with pytest.raises(CatalogueConfigError):
        write_defaults(tmp_path)
